def add_p(text, style=None, align=None, italic=False, bold=False, size=None):
    np = disc.insert_paragraph_before("", style=style or body_style)
    if align is not None: np.alignment = align
    if text:
        run = np.add_run(text)
        run.italic = italic; run.bold = bold
        if size: run.font.size = Pt(size)
    return np

def add_img(path, caption, width=6.0):
    np = disc.insert_paragraph_before("", style=body_style)
    np.alignment = WDA.CENTER
    try:
        np.add_run().add_picture(CH + path, width=Inches(width))
    except Exception as e:
        np.add_run(f"[слика недоступна: {path}]")
    cp = disc.insert_paragraph_before(caption, style=cap_style)
    cp.alignment = WDA.CENTER
    for r in cp.runs: r.italic = True

def add_table(rows):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    try: t.style = "Table Grid"
    except Exception: pass
    for i, row in enumerate(rows):
        for j, cell in enumerate(row):
            c = t.cell(i, j)
            c.text = ""
            run = c.paragraphs[0].add_run(cell)
            if i == 0: run.bold = True
            run.font.size = Pt(9)
    disc._p.addprevious(t._tbl)   # move table to just before discussion

